export function translate(lang: "en" | "fa", key: string): string {
  return lang === "fa" ? fa[key] ?? key : key;
}

export function useT() {
  const lang = useSettings((s) => s.lang);
  return (key: string) => translate(lang, key);
}

export function useLang() {
  const lang = useSettings((s) => s.lang);
  return lang;
}

const FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹";
export function num(n: number | string, lang: "en" | "fa"): string {
  const s = String(n);
  return lang === "fa" ? s.replace(/\d/g, (d) => FA_DIGITS[+d]) : s;
}

export function isRTLText(s: string): boolean {
  return /[\u0590-\u08FF\uFB1D-\uFDFF\uFE70-\uFEFF]/.test(s);
}

